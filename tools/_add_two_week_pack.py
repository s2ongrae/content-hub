# ────────────────────────────── 파일에 삽입 ──────────────────────────────
def dump_series_block(series_list, base_indent=2):
    txt = json.dumps(series_list, ensure_ascii=False, indent=2)
    lines = txt.split("\n")[1:-1]  # 앞 '[' 와 뒤 ']' 제거
    pad = " " * base_indent
    return "\n".join(pad + ln if ln.strip() else ln for ln in lines)


